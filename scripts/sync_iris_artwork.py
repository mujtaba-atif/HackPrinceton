#!/usr/bin/env python3
"""Keep the iPhone's vector artwork identical to the approved Iris design bundle."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "Design/Iris/assets.json"
OUTPUT = ROOT / "Iris/UI/Glass/IrisArtwork.swift"


def render():
    assets = json.loads(SOURCE.read_text())
    artwork = {
        "locateCard": assets["art"]["locateContent"],
        "exploreCard": assets["art"]["exploreContent"],
        **{name: svg for name, svg in assets["heroCrew"].items()},
        "locatePanel": assets["splitPanels"]["locate"],
        "explorePanel": assets["splitPanels"]["explore"],
        "treasureMap": assets["treasureMap"],
        "edgeLights": assets["cameraEdgeLights"],
    }
    header = """// Generated by scripts/sync_iris_artwork.py from Design/Iris/assets.json.
// Figma: zLF4VopCM0YI8eZAH2Aexg · approved revision 18.
// Edit the shared design assets, then regenerate; do not maintain a second copy by hand.

import Foundation

enum IrisArtwork {
    static let revision = 18
"""
    return header + "\n".join(
        f'    static let {name} = VectorArt(svg: #"""\n{svg}\n"""#)\n'
        for name, svg in artwork.items()
    ) + "}\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            raise SystemExit("Native Iris artwork is stale. Run python3 scripts/sync_iris_artwork.py")
        print("Native Iris artwork matches the approved design bundle.")
    else:
        OUTPUT.write_text(expected)
        print(f"Updated {OUTPUT.relative_to(ROOT)}")
